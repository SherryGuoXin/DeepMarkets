CREATE VIEW FILING_VALUE_RECONCILIATION AS
WITH HOLDING_TOTAL AS (
    SELECT
        C.ACCESSION_NUMBER,
        SUM(I.VALUE) AS HOLDING_RAW_TOTAL,
        COUNT(*) AS HOLDING_ROW_COUNT
    FROM CANONICAL_FILING_COMPONENT C
    JOIN INFOTABLE I USING (ACCESSION_NUMBER)
    WHERE C.IS_EFFECTIVE = 1
    GROUP BY C.ACCESSION_NUMBER
)
SELECT
    H.ACCESSION_NUMBER,
    H.HOLDING_ROW_COUNT,
    H.HOLDING_RAW_TOTAL,
    S.TABLEVALUETOTAL AS SUMMARY_RAW_TOTAL,
    H.HOLDING_RAW_TOTAL - S.TABLEVALUETOTAL AS RAW_DIFFERENCE,
    CASE
        WHEN S.TABLEVALUETOTAL IS NULL THEN 'NO_SUMMARY'
        WHEN H.HOLDING_RAW_TOTAL = S.TABLEVALUETOTAL THEN 'MATCH'
        WHEN ABS(H.HOLDING_RAW_TOTAL - S.TABLEVALUETOTAL) <= 1
            THEN 'ROUNDING_DIFFERENCE'
        WHEN S.TABLEVALUETOTAL = 0 THEN 'SUMMARY_ZERO'
        WHEN H.HOLDING_RAW_TOTAL
             BETWEEN S.TABLEVALUETOTAL * 999
                 AND S.TABLEVALUETOTAL * 1001
            THEN 'HOLDINGS_APPROX_1000X_SUMMARY'
        WHEN S.TABLEVALUETOTAL
             BETWEEN H.HOLDING_RAW_TOTAL * 999
                 AND H.HOLDING_RAW_TOTAL * 1001
            THEN 'SUMMARY_APPROX_1000X_HOLDINGS'
        ELSE 'MISMATCH'
    END AS RECONCILIATION_STATUS
FROM HOLDING_TOTAL H
LEFT JOIN SUMMARYPAGE S USING (ACCESSION_NUMBER);

CREATE VIEW CANONICAL_HOLDING_LINE AS
SELECT
    F.CANONICAL_FILING_ID,
    F.MANAGER_CIK,
    F.QUARTER_ID,
    Q.QUARTER_LABEL,
    Q.QUARTER_END_DATE,
    F.RESOLUTION_STATUS,
    F.IS_ANALYTICS_READY,
    F.HAS_CONFIDENTIAL_OMISSION,
    C.ACCESSION_NUMBER,
    R.RECONCILIATION_STATUS AS VALUE_RECONCILIATION_STATUS,
    I.INFOTABLE_SK,
    D.CUSIP_ID,
    I.CUSIP,
    I.NAMEOFISSUER,
    I.TITLEOFCLASS,
    I.FIGI,
    I.VALUE AS RAW_REPORTED_VALUE,
    CASE
        WHEN N.FILING_DATE_ISO < '2023-01-03' THEN 1000
        ELSE 1
    END AS VALUE_MULTIPLIER,
    I.VALUE * CASE
        WHEN N.FILING_DATE_ISO < '2023-01-03' THEN 1000
        ELSE 1
    END AS VALUE_USD,
    I.SSHPRNAMT,
    I.SSHPRNAMTTYPE,
    I.PUTCALL,
    I.INVESTMENTDISCRETION,
    I.OTHERMANAGER,
    I.VOTING_AUTH_SOLE,
    I.VOTING_AUTH_SHARED,
    I.VOTING_AUTH_NONE
FROM CANONICAL_FILING F
JOIN QUARTER Q USING (QUARTER_ID)
JOIN CANONICAL_FILING_COMPONENT C
    ON C.CANONICAL_FILING_ID = F.CANONICAL_FILING_ID
   AND C.IS_EFFECTIVE = 1
JOIN NORMALIZED_FILING N USING (ACCESSION_NUMBER)
JOIN INFOTABLE I USING (ACCESSION_NUMBER)
LEFT JOIN FILING_VALUE_RECONCILIATION R USING (ACCESSION_NUMBER)
LEFT JOIN CUSIP D ON D.CUSIP = I.CUSIP;

CREATE VIEW ANALYTICS_HOLDING_LINE AS
SELECT *
FROM CANONICAL_HOLDING_LINE
WHERE IS_ANALYTICS_READY = 1;

-- Current CUSIP classification, stable instrument keys, and materialized
-- quarterly relationship facts populated by etl/build_instruments.py.
CREATE TABLE SECURITY_TYPE (
    SECURITY_TYPE_ID INTEGER PRIMARY KEY,
    SECURITY_TYPE_CODE TEXT NOT NULL UNIQUE,
    SECURITY_TYPE_NAME TEXT NOT NULL,
    INCLUDE_IN_CORE_HOLDINGS INTEGER NOT NULL
        CHECK (INCLUDE_IN_CORE_HOLDINGS IN (0, 1))
);

CREATE TABLE SECURITY_CLASS_RULE (
    RULE_ID INTEGER PRIMARY KEY,
    PRIORITY INTEGER NOT NULL,
    FIELD_NAME TEXT NOT NULL
        CHECK (FIELD_NAME IN ('TITLEOFCLASS', 'NAMEOFISSUER')),
    MATCH_TYPE TEXT NOT NULL
        CHECK (MATCH_TYPE IN ('EXACT', 'CONTAINS', 'REGEX')),
    MATCH_PATTERN TEXT NOT NULL,
    SECURITY_TYPE_ID INTEGER NOT NULL,
    SOURCE TEXT NOT NULL,
    DESCRIPTION TEXT,
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)),
    FOREIGN KEY (SECURITY_TYPE_ID)
        REFERENCES SECURITY_TYPE (SECURITY_TYPE_ID)
);

CREATE INDEX SECURITY_CLASS_RULE_PRIORITY_IDX
    ON SECURITY_CLASS_RULE (IS_ACTIVE, PRIORITY, RULE_ID);

CREATE TABLE CUSIP_SECURITY_TYPE_OVERRIDE (
    CUSIP_ID INTEGER PRIMARY KEY,
    SECURITY_TYPE_ID INTEGER NOT NULL,
    REASON TEXT NOT NULL,
    SOURCE TEXT NOT NULL,
    REVIEWED_AT TEXT NOT NULL,
    FOREIGN KEY (CUSIP_ID) REFERENCES CUSIP (CUSIP_ID),
    FOREIGN KEY (SECURITY_TYPE_ID)
        REFERENCES SECURITY_TYPE (SECURITY_TYPE_ID)
);

CREATE TABLE CUSIP_CLASSIFICATION (
    CUSIP_ID INTEGER PRIMARY KEY,
    SECURITY_TYPE_ID INTEGER NOT NULL,
    CLASSIFICATION_METHOD TEXT NOT NULL
        CHECK (
            CLASSIFICATION_METHOD IN (
                'CUSIP_OVERRIDE', 'RULE_VOTE', 'UNKNOWN'
            )
        ),
    SELECTED_RULE_ID INTEGER,
    TOTAL_OCCURRENCE_COUNT INTEGER NOT NULL,
    MATCHED_OCCURRENCE_COUNT INTEGER NOT NULL,
    WINNING_OCCURRENCE_COUNT INTEGER NOT NULL,
    CLASSIFICATION_CONFIDENCE REAL NOT NULL,
    CLASSIFIED_AT TEXT NOT NULL,
    FOREIGN KEY (CUSIP_ID) REFERENCES CUSIP (CUSIP_ID),
    FOREIGN KEY (SECURITY_TYPE_ID)
        REFERENCES SECURITY_TYPE (SECURITY_TYPE_ID),
    FOREIGN KEY (SELECTED_RULE_ID)
        REFERENCES SECURITY_CLASS_RULE (RULE_ID)
);

CREATE TABLE INSTRUMENT (
    INSTRUMENT_ID INTEGER PRIMARY KEY,
    CUSIP_ID INTEGER NOT NULL,
    SECURITY_TYPE_ID INTEGER NOT NULL,
    OPTION_TYPE TEXT NOT NULL
        CHECK (OPTION_TYPE IN ('NONE', 'CALL', 'PUT')),
    AMOUNT_TYPE TEXT NOT NULL
        CHECK (AMOUNT_TYPE IN ('SH', 'PRN', 'OTHER')),
    CLASSIFICATION_METHOD TEXT NOT NULL,
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)),
    UNIQUE (CUSIP_ID, SECURITY_TYPE_ID, OPTION_TYPE, AMOUNT_TYPE),
    FOREIGN KEY (CUSIP_ID) REFERENCES CUSIP (CUSIP_ID),
    FOREIGN KEY (SECURITY_TYPE_ID)
        REFERENCES SECURITY_TYPE (SECURITY_TYPE_ID)
);

CREATE INDEX INSTRUMENT_CUSIP_IDX ON INSTRUMENT (CUSIP_ID);

CREATE TABLE CIK_INSTRUMENT (
    CIK_INSTRUMENT_ID INTEGER PRIMARY KEY,
    MANAGER_CIK CHAR(10) NOT NULL,
    INSTRUMENT_ID INTEGER NOT NULL,
    FIRST_OBSERVED_QUARTER_ID INTEGER NOT NULL,
    LATEST_OBSERVED_QUARTER_ID INTEGER NOT NULL,
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)),
    UNIQUE (MANAGER_CIK, INSTRUMENT_ID),
    FOREIGN KEY (INSTRUMENT_ID)
        REFERENCES INSTRUMENT (INSTRUMENT_ID),
    FOREIGN KEY (FIRST_OBSERVED_QUARTER_ID)
        REFERENCES QUARTER (QUARTER_ID),
    FOREIGN KEY (LATEST_OBSERVED_QUARTER_ID)
        REFERENCES QUARTER (QUARTER_ID)
);

CREATE INDEX CIK_INSTRUMENT_MANAGER_IDX
    ON CIK_INSTRUMENT (MANAGER_CIK);

CREATE TABLE CIK_INSTRUMENT_QUARTER (
    CIK_INSTRUMENT_QUARTER_ID INTEGER PRIMARY KEY,
    CIK_INSTRUMENT_ID INTEGER NOT NULL,
    QUARTER_ID INTEGER NOT NULL,
    VALUE_USD INTEGER NOT NULL,
    REPORTED_AMOUNT INTEGER NOT NULL,
    AMOUNT_TYPE TEXT NOT NULL,
    PORTFOLIO_WEIGHT REAL,
    SOURCE_ROW_COUNT INTEGER NOT NULL,
    EFFECTIVE_ACCESSION_COUNT INTEGER NOT NULL,
    HAS_SHARED_DISCRETION INTEGER NOT NULL
        CHECK (HAS_SHARED_DISCRETION IN (0, 1)),
    HAS_CONFIDENTIAL_OMISSION INTEGER NOT NULL
        CHECK (HAS_CONFIDENTIAL_OMISSION IN (0, 1)),
    VALUE_QUALITY_STATUS TEXT NOT NULL
        CHECK (
            VALUE_QUALITY_STATUS IN (
                'OK', 'ROUNDING_DIFFERENCE', 'ISSUE'
            )
        ),
