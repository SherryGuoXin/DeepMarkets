    QUARTER_ID INTEGER PRIMARY KEY,
    QUARTER_LABEL CHAR(6) NOT NULL UNIQUE,
    QUARTER_END_DATE DATE NOT NULL UNIQUE,
    YEAR INTEGER NOT NULL,
